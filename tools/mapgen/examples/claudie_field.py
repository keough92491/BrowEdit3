import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from rogen import MapGen
# textures are addressed by index into the open map's texture list ("#N")
m = MapGen("claudie", 100, 100, seed=11)
G = m.add_texture("#0"); HILL = m.add_texture("#1"); G2 = m.add_texture("#2"); DIRT = m.add_texture("#3")
H3 = m.add_texture("#4"); G4 = m.add_texture("#6"); H10 = m.add_texture("#7")
m.noise(scale=26, amplitude=12)
m.hill(78, 24, 20, 34)
m.hill(18, 80, 16, 24)
m.flatten(38, 38, 62, 62, height=0.0, blend=6)
m.smooth(2)
m.border(margin=5, drop=-6)
m.set_wall_texture(H3)
m.paint_all(G)
m.paint_by_height(HILL, min_height=14)
m.paint_by_slope(H10, 0.5)
pts = [(4, 50), (30, 46), (50, 50), (70, 56), (96, 52)]
m.path(pts, width=3, texture=DIRT)
m.place("roo_fild\\bush1.rsm", 50, 50, scale=(3, 3, 3), name="bush", footprint=(1.2, 1.2))
m.scatter(["roo_fild\\tree.rsm", "roo_payon\\pine3.rsm"], 70, region=(5, 5, 95, 95), min_dist=5, footprint=(0.8, 0.8),
          avoid=("water", "path"), max_slope=0.5)
m.scatter(["ROO_fild\\rock4.rsm"], 14, region=(5, 5, 95, 95), min_dist=6, footprint=(1.5, 1.5), avoid=("water", "path"))
m.scatter(["roo_fild\\bush1.rsm"], 30, region=(5, 5, 95, 95), min_dist=3, scale_range=(2.5, 3.5), footprint=(1, 1), avoid=("water", "path"))
m.line(["ROO_fild\\fence.rsm"], [(36, 40), (36, 60), (64, 60)], spacing=3, rot_offset=90)
m.set_sun(longitude=40, latitude=50, ambient=(0.7, 0.7, 0.7))
import json
cmds = m.live_commands()
cmds.insert(1, {"cmd": "delete_models", "filter": ""})
json.dump({"commands": cmds}, open(sys.argv[1] if len(sys.argv) > 1 else "/mnt/user-data/outputs/c004.json", "w"), separators=(",", ":"))
print(len(m.models), "models")
